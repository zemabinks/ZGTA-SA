#!/usr/bin/env node
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'zgta-water-'));
try {
  fs.mkdirSync(path.join(temporary, 'local-only/site/game/world'), {recursive: true});
  fs.mkdirSync(path.join(temporary, 'local-only/selfhost'), {recursive: true});
  for (const file of ['selfhost_backend.js','player_placement.js', 'optional_discord.js', 'weapon_inventory.js', 'world_collision.js', 'local_projectiles.js']) fs.copyFileSync(path.join(require('node:path').resolve(__dirname, '../..'),file),path.join(temporary,file));
  fs.copyFileSync(path.join(require('node:path').resolve(__dirname, '../..'),'local-only/selfhost/client-catalog.json'),path.join(temporary,'local-only/selfhost/client-catalog.json'));
  fs.copyFileSync(path.join(require('node:path').resolve(__dirname, '../..'),'local-only/site/game/world/index.json'),path.join(temporary,'local-only/site/game/world/index.json'));
  const game = require(path.join(temporary,'selfhost_backend.js'));
  const {player} = game.ensurePlayer({headers:{cookie:''}},{setHeader(){}});
  const sent = [], peer = {player,ready:true,lastSeen:Date.now(),state:{},send:p=>sent.push(p)};
  game.peers.add(peer); player.armour = 50;
  const report = {t:'me',walking:true,x:-1500,y:-1700,z:-2,weapon:0};
  game.onMessage(peer,report);
  assert(peer.submergedSince); assert.equal(player.health,100);
  peer.submergedSince -= 21000;
  game.onMessage(peer,report);
  assert.equal(player.health,95); assert.equal(player.armour,50);
  assert(sent.some(p=>p.t==='vitals' && p.health===95));
  game.onMessage(peer,report); assert.equal(player.health,95,'damage is rate limited');
  game.onMessage(peer,{...report,z:0}); assert.equal(peer.submergedSince,null);
  game.onMessage(peer,{...report,walking:false,driving:true}); assert.equal(peer.submergedSince,null);
  game.onMessage(peer,{...report,x:1480,y:-1738,z:-2}); assert.equal(peer.submergedSince,null,'underground land is not water');
  player.health=5;
  game.onMessage(peer,report); peer.submergedSince -= 21000; peer.lastDrownDamageAt=0;
  game.onMessage(peer,report);
  assert.equal(player.health,0); assert.equal(player.deaths,1);
  player.health=100;peer.inventoryEnabled=true;peer.nativeOxygen=25;peer.nativeOxygenTime=0;
  const swim={...report,act:14};
  game.onMessage(peer,swim);
  peer.nativeOxygenAt=Date.now()-500;game.onMessage(peer,swim);
  assert.equal(peer.nativeOxygen,0,'native underwater oxygen drains at 100 units/second');
  assert(player.health<100 && player.health>80,'native drowning follows the 49.5/s public swim rate');
  assert.equal(player.armour,50,'native drowning leaves armour unchanged');
  peer.nativeOxygenAt=Date.now()-500;game.onMessage(peer,{...report,z:0,act:0});
  assert(Math.abs(peer.nativeOxygen-50)<0.001,'native surface breath recovers at 100 units/second');
  peer.nativeOxygen=100;peer.nativeOxygenAt=Date.now()-500;game.onMessage(peer,{...swim,act:15});
  assert(Math.abs(peer.nativeOxygen-75)<0.001,'glide drains at half the underwater effort rate');
  game.flushSync();clearInterval(game.tick);
  console.log('PASS: real water geometry, breath, drowning rate, surface/vehicle reset and death');
} finally { fs.rmSync(temporary,{recursive:true,force:true}); }
